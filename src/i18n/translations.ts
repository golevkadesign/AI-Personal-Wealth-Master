export type AppLanguage = keyof typeof translations;
export type TranslationKey = keyof typeof translations['zh-CN'];

type TranslationParams = Record<string, string | number | boolean | null | undefined>;

function resolveTranslationValue(language: AppLanguage, key: string): unknown {
  const keys = key.split('.');
  let current: any = translations[language];

  for (const item of keys) {
    if (current === undefined || current === null) return undefined;
    current = current[item];
  }

  return current;
}

function applyParams(template: string, params?: TranslationParams): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) => {
    const value = params[token];
    return value === undefined || value === null ? '' : String(value);
  });
}

export function translateI18n(language: AppLanguage | string | undefined, key: string, params?: TranslationParams): string {
  const resolvedLanguage: AppLanguage = language === 'en-US' || language === 'zh-CN' ? language : 'zh-CN';
  const value = resolveTranslationValue(resolvedLanguage, key);
  return typeof value === 'string' ? applyParams(value, params) : key;
}

const emptyStateMarkers: Record<string, readonly string[]> = {
  'dashboard.personaFallback': [
    '当前信息不足以',
    'insufficient information',
  ],
};

export function isKnownI18nText(value: unknown, key: string): boolean {
  if (typeof value !== 'string' || !value.trim()) return false;
  const normalized = value.trim();
  const exactMatch = (Object.keys(translations) as AppLanguage[]).some((language) => (
    translateI18n(language, key).trim() === normalized
  ));

  if (exactMatch) return true;

  const markers = emptyStateMarkers[key] || [];
  const lower = normalized.toLowerCase();
  return markers.some((marker) => lower.includes(marker.toLowerCase()));
}
